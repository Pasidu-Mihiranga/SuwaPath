# bcrypt is deliberately slow; every seeded account shares one demo password, so
# the hash is computed once rather than 400+ times.
_SHARED_HASH: str | None = None


def shared_password_hash() -> str:
    global _SHARED_HASH
    if _SHARED_HASH is None:
        _SHARED_HASH = bcrypt.hashpw(
            DEMO_PASSWORD.encode("utf-8"), bcrypt.gensalt(rounds=10)
        ).decode("utf-8")
    return _SHARED_HASH


def utc(dt: datetime) -> datetime:
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt


