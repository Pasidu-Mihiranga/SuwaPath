def seed_notifications(
    db: Session,
    appointments: list[Appointment],
    demo: dict[str, User],
    care_data: dict[str, list],
) -> int:
    """In-app notifications across every category (spec §21)."""
    now = datetime.now(timezone.utc)
    notifications: list[Notification] = []

    # Appointment reminders for upcoming bookings.
    upcoming = [
        a for a in appointments
        if a.scheduled_start > now and a.status in
        (AppointmentStatus.CONFIRMED, AppointmentStatus.PENDING)
    ]
    for appointment in upcoming[:220]:
        hours_away = (appointment.scheduled_start - now).total_seconds() / 3600
        when = appointment.scheduled_start.strftime("%I:%M %p").lstrip("0")
        day_label = (
            "tomorrow"
            if hours_away < 48
            else appointment.scheduled_start.strftime("on %d %b")
        )
        notifications.append(
            Notification(
                user_id=appointment.patient_user_id,
                category=NotificationCategory.APPOINTMENT,
                priority=(
                    NotificationPriority.HIGH if hours_away < 48
                    else NotificationPriority.NORMAL
                ),
                title="Upcoming appointment",
                body=f"Your appointment is {day_label} at {when}.",
                action_type="appointment",
                action_id=appointment.id,
                is_read=rng.random() < 0.4,
                scheduled_for=appointment.scheduled_start - timedelta(days=1),
            )
        )

    # Maternal programme reminders.
    for record in care_data["maternal"][:60]:
        if record.is_postpartum:
            notifications.append(
                Notification(
                    user_id=record.patient_user_id,
                    category=NotificationCategory.CARE_PROGRAMME,
                    priority=NotificationPriority.NORMAL,
                    title="Newborn vaccination due",
                    body="Your baby's next vaccination is due in 3 days.",
                    action_type="care_programme",
                    action_id=record.enrollment_id,
                )
            )
        else:
            week = record.pregnancy_week or 0
            notifications.append(
                Notification(
                    user_id=record.patient_user_id,
                    category=NotificationCategory.CARE_PROGRAMME,
                    priority=NotificationPriority.NORMAL,
                    title="Antenatal visit approaching",
                    body=f"You are at week {week}. Your next antenatal visit is in 2 days.",
                    action_type="care_programme",
                    action_id=record.enrollment_id,
                )
            )

    # Medication reminder for the elderly demo persona.
    notifications.append(
        Notification(
            user_id=demo["elderly"].id,
            category=NotificationCategory.MEDICATION,
            priority=NotificationPriority.HIGH,
            title="Medication due",
            body="Time to take Amlodipine 5mg (1 tablet, after breakfast).",
            action_type="medication",
        )
    )

    db.add_all(notifications)
    db.flush()
    log(f"Notifications: {len(notifications)}")
    return len(notifications)


