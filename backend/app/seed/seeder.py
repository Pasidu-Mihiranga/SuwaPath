    parser.add_argument(
        "--reset", action="store_true", help="Truncate existing data before seeding"
    )
    args = parser.parse_args()

    create_all()
    db = SessionLocal()
    try:
        seed_all(db, reset=args.reset)
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()
    return 0


