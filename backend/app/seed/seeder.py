# --------------------------------------------------------------------------
def seed_all(db: Session, *, reset: bool = False) -> None:
    from app.seed import journeys, people

    if reset:
        reset_database(db)

    print("\nSeeding SuwaPath dataset...")
    password_hash = shared_password_hash()

    specialties = seed_specialties(db)
    tests = seed_tests(db)
    hospitals, centres = seed_facilities(db, tests)
    programmes = seed_care_programmes(db)
    seed_system_config(db)

    system_admin, hospital_admins = people.seed_admins(db, rng, password_hash, hospitals)
    log(f"Admins: 1 system + {len(hospital_admins)} hospital")

    doctors = people.seed_doctors(db, rng, password_hash, hospitals, specialties)
    log(f"Doctors: {len(doctors)}")

    patients, demo = people.seed_patients(db, rng, password_hash)
    log(f"Patients: {len(patients)}")

    profiles = {
        p.user_id: p
        for p in db.query(PatientProfile).all()
    }

    guardians = people.seed_guardians(db, rng, password_hash, patients, profiles, demo)
    relationship_count = db.query(GuardianRelationship).count()
    log(f"Guardians: {len(guardians)} users, {relationship_count} relationships")

    db.commit()

    hospitals_by_id = {h.id: h for h in hospitals + centres}
    doctors_by_id = {d.id: d for d in doctors}

    appointments = journeys.seed_appointments(
        db, rng, patients, profiles, doctors, hospitals_by_id
    )
    upcoming = sum(
        1 for a in appointments
        if a.scheduled_start >= datetime.now(timezone.utc)
    )
    log(f"Appointments: {len(appointments)} ({len(appointments) - upcoming} historical, {upcoming} upcoming)")

    consultations = journeys.seed_consultations(
        db, rng, appointments, doctors_by_id, limit=N_CONSULTATIONS
    )
    log(f"Consultations: {len(consultations)}")

    referrals = journeys.seed_referrals(db, rng, consultations, doctors, hospitals)
    log(f"Referrals: {len(referrals)}")

