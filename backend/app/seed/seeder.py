def make_name(sex: Sex, ethnicity: str | None = None) -> str:
    ethnicity = ethnicity or rng.choices(
        ["sinhala", "tamil", "muslim", "burgher"], weights=[0.70, 0.16, 0.10, 0.04]
    )[0]

    if ethnicity == "tamil":
        first = rng.choice(
            ref.TAMIL_FEMALE_FIRST if sex == Sex.FEMALE else ref.TAMIL_MALE_FIRST
        )
        return f"{first} {rng.choice(ref.TAMIL_SURNAMES)}"
    if ethnicity == "muslim":
        first = rng.choice(
            ref.MUSLIM_FEMALE_FIRST if sex == Sex.FEMALE else ref.MUSLIM_MALE_FIRST
        )
        return f"{first} {rng.choice(ref.MUSLIM_SURNAMES)}"
    if ethnicity == "burgher":
        first = rng.choice(
            ref.SINHALA_FEMALE_FIRST if sex == Sex.FEMALE else ref.SINHALA_MALE_FIRST
        )
        return f"{first} {rng.choice(ref.BURGHER_SURNAMES)}"

    first = rng.choice(
        ref.SINHALA_FEMALE_FIRST if sex == Sex.FEMALE else ref.SINHALA_MALE_FIRST
    )
    return f"{first} {rng.choice(ref.SINHALA_SURNAMES)}"


_used_emails: set[str] = set()


def make_email(full_name: str, domain: str = "example.lk") -> str:
    base = full_name.lower().replace(" ", ".").replace("'", "")
    candidate = f"{base}@{domain}"
    counter = 2
    while candidate in _used_emails:
        candidate = f"{base}{counter}@{domain}"
        counter += 1
    _used_emails.add(candidate)
    return candidate


def make_phone() -> str:
    return f"+947{rng.choice('01245678')}{rng.randint(1000000, 9999999)}"


def jitter_location(loc: ref.Location, spread: float = 0.035) -> tuple[float, float]:
    """Scatter a person around a city centre so distances vary realistically."""
    return (
        round(loc.latitude + rng.uniform(-spread, spread), 6),
        round(loc.longitude + rng.uniform(-spread, spread), 6),
    )


def weighted_location() -> ref.Location:
    return rng.choices(ref.LOCATIONS, weights=[l.population_weight for l in ref.LOCATIONS])[0]


